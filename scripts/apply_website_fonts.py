client = discord.Client(intents=discord.Intents.default())

@client.event
async def on_ready():
    guild = client.get_guild(GUILD_ID)
    if not guild:
        print("Guild not found!")
        await client.close()
        return

    print(f"Applying website aesthetic fonts to: {guild.name}...")
    for ch_id, new_name in FONTS_MAP.items():
        ch = guild.get_channel(ch_id)
        if not ch:
            continue
        if ch.name != new_name:
            try:
                await ch.edit(name=new_name)
                print(f"  ✓ {new_name}")
                await asyncio.sleep(0.4)
            except Exception as e:
                print(f"  ⚠️ Error updating {ch_id} ({ch.name}): {e}")

    print("Website aesthetic fonts successfully applied!")
    await client.close()

client.run(os.getenv("DISCORD_BOT_TOKEN"))
